import fs from 'node:fs';
import assert from 'node:assert/strict';
import * as api from '../consumer/node_modules/ubukit-js/src/index.js';
const base=new URL('../consumer/node_modules/ubukit-js/',import.meta.url);
const pkg=JSON.parse(fs.readFileSync(new URL('package.json',base),'utf8'));
const manifest=JSON.parse(fs.readFileSync(new URL('SOURCE_MANIFEST.json',base),'utf8'));
const readme=fs.readFileSync(new URL('README.md',base),'utf8');
assert.equal(pkg.version,'0.1.0-dev.6');assert.equal(Object.keys(pkg.exports).length,7);assert.equal(Object.keys(manifest.runtime_files).length,27);assert.equal(api.algorithms.length,9);
assert.match(readme,/0\.1\.0-dev\.6/);assert.match(readme,/27 runtime files, seven package entrypoints and nine/);assert.match(readme,/ubukit-js-0\.1\.0-dev\.6\.tgz/);
assert.doesNotMatch(readme,/No JavaScript ARI|ubukit-js-0\.1\.0-dev\.4\.tgz|25 runtime files/);
for(const name of ['som','som_batch','adjustedRandScore','adjustedMutualInfoScore','adjustedScores'])assert.ok(readme.includes(name));
for(const path of ['SOM.md','EXTERNAL_METRICS.md','OPTIMIZATION.md'])assert.ok(fs.existsSync(new URL(path,base)));
const consumer=JSON.parse(fs.readFileSync(new URL('../consumer/package.json',import.meta.url),'utf8'));
assert.equal(consumer.dependencies['ubukit-js'],'file:../artifacts/ubukit-js-0.1.0-dev.6.tgz');
console.log(JSON.stringify({status:'passed',version:pkg.version,runtimeFiles:27,entrypoints:7,registryNames:9,consumerVersionReference:'dev6',ariAmiDocs:true,somDocs:true}));
