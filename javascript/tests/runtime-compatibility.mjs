import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {Worker} from 'node:worker_threads';
import vm from 'node:vm';
const url=new URL('../consumer/node_modules/ubukit-js/src/external-metrics.js',import.meta.url),source=readFileSync(url,'utf8');
assert.doesNotMatch(source,/^\s*import\s/m);
const executable=source.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g,'');
assert.doesNotMatch(executable,/\b(?:process|require|Buffer|window|document|navigator)\b/);
const context=vm.createContext({});
const module=new vm.SourceTextModule(source,{context});
await module.link(()=>{throw new Error('external dependency unexpectedly required');});await module.evaluate();
const clean=vm.runInContext('[[0,0,1,1],[0,1,0,1]]',context),pureResult=module.namespace.adjustedScores(...clean);
assert.equal(pureResult.ari,-.5);assert.ok(Math.abs(pureResult.ami+.5)<1e-15);
const workerCode=`import {parentPort} from 'node:worker_threads';import {adjustedScores} from ${JSON.stringify(url.href)};parentPort.on('message',({a,b})=>parentPort.postMessage(adjustedScores(a,b)));`;
const worker=new Worker(new URL('data:text/javascript,'+encodeURIComponent(workerCode)),{type:'module'});
const result=await new Promise((resolve,reject)=>{worker.once('message',resolve);worker.once('error',reject);worker.postMessage({a:[0,0,1,1],b:[0,1,0,1]});});await worker.terminate();
assert.equal(result.ari,-.5);assert.ok(Math.abs(result.ami+.5)<1e-15);
